"""Portable reports and executable regression tests from observed counterexamples."""

import json


def markdown_report(report):
    lines = [
        "# Keel failure-discovery report",
        "",
        f"Campaign: {report['id']}",
        f"Seed: {report['seed']}",
        f"Faults detected: {report['killed']}/{report['total']}",
        "",
        report["scope"],
        "",
        "Reduction is 1-minimal for the reported invariant, not globally shortest.",
        "A surviving mutant means no counterexample was found within this budget.",
        "",
    ]
    for finding in report["findings"]:
        lines += [
            f"## {finding['mutation']}: {finding['status']}",
            "",
            f"Schedules attempted: {finding['attempted']}",
            "",
        ]
        if finding["status"] != "killed":
            continue
        violation = finding["minimal"]["violations"][0]
        lines += [
            f"Invariant: {violation['invariant']}",
            f"Expected: {violation['expected']}",
            f"Observed: {violation['actual']}",
            "",
            "Original: " + " → ".join(finding["original_trace"]),
            "Reduced: " + " → ".join(finding["minimal_trace"]),
            "",
            "Correct implementation: no invariant violations on the reduced sequence.",
            "",
            "### Execution evidence",
            "",
        ]
        for step in finding["minimal"]["steps"]:
            lines += [
                f"{step['index'] + 1}. **{step['action']}**: {step['note']}",
                "   State: `" + json.dumps(step["state"], sort_keys=True) + "`",
            ]
        lines.append("")
    return "\n".join(lines)


def regression_tests(report):
    lines = [
        '"""Generated by Keel from observed failures; run with pytest.',
        "Baseline is the default. Set KEEL_MUTATION to a reported mutation to verify detection.",
        '"""',
        "import os",
        "",
        "from payops.lab.replay import replay_trace",
        "",
    ]
    for finding in report["findings"]:
        if finding["status"] != "killed":
            continue
        lines += [
            f"def test_{finding['mutation']}():",
            f"    actions = {finding['minimal_trace']!r}",
            '    mutation = os.environ.get("KEEL_MUTATION", "baseline")',
            "    result = replay_trace(actions, mutation)",
            '    assert result["violations"] == [], result["violations"]',
            "",
        ]
    if not any(f["status"] == "killed" for f in report["findings"]):
        lines += ["# No counterexample found; no regression test can be generated.", ""]
    return "\n".join(lines)
